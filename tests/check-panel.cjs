const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const src = path.join(root, 'src/vba');
const code = fs.readFileSync(path.join(src, 'frmMimakiImposerPanel_CODE_ONLY.txt'), 'utf8');
assert.match(code, /^Option Explicit/);
assert.doesNotMatch(code, /Private WithEvents/);
assert.doesNotMatch(code, /Controls\.Add|LoadPicture|EnsureEmbeddedIconFile/);
assert.doesNotMatch(code, /\b(?:Me|[a-zA-Z_]\w*)\.(?:Left|Top|Width|Height)\s*=/);
const frm = fs.readFileSync(path.join(src, 'frmMimakiImposerPanel.frm'), 'utf8');
assert.match(frm, /OleObjectBlob\s*=\s*"frmMimakiImposerPanel\.frx"/);
const frx = fs.readFileSync(path.join(src, 'frmMimakiImposerPanel.frx'));
assert.ok(frx.length > 5000);
const attrs = frm.indexOf('Attribute VB_Exposed = False');
assert.ok(attrs >= 0);
const frmCode = frm.slice(frm.indexOf('\n', attrs) + 1).replace(/\r\n/g, '\n').trim();
assert.equal(frmCode, code.replace(/\r\n/g, '\n').trim());
assert.match(code, /preserveVector = chkPreserveVector.Value/);
assert.match(code, /RefreshPanelForLayoutChange/);
assert.match(code, /InitializePanelAppearance/);
const harness = fs.readFileSync(path.join(root, 'tools/test-panel.ps1'), 'utf8');
assert.match(harness, /MimakiPanelUITest_/);
assert.match(harness, /testCode\.Replace\('Private Const SETTINGS_APP/);
assert.ok(harness.indexOf('testCode.Replace') < harness.indexOf("'PanelUiProbe.ValidatePanel'"));
assert.match(harness, /probeCode\.Replace/);
console.log('PASS: designer resources, code export, persistent geometry and existing workflow wiring.');
